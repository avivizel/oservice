def label(mapping: dict[str, str], key: str | None, default: str = "—") -> str:
    if not key:
        return default
    return mapping.get(key, key)


def city_coords(city: str | None) -> tuple[float, float] | None:
    if not city:
        return None
    name = city.strip()
    if name in CITY_COORDS:
        return CITY_COORDS[name]
    for known, pair in CITY_COORDS.items():
        if known in name or name in known:
            return pair
    return None
