def seed_if_empty(db: Session) -> int:
    created = 0
    for raw in SEED_SERVICES:
        ext = raw.get("external_id") or ""
        if ext and db.query(Service).filter(Service.external_id == ext).first():
            continue
        svc = _svc(**raw)
        db.add(svc)
        db.flush()
        db.add(
            ServiceSource(
                service_id=svc.id,
                name=svc.source_name or "מאגר בסיס",
                url=svc.source_url,
                authority=svc.authority,
                excerpt="נתוני בסיס לקווי חירום וגופים ארציים. יש לאמת בסריקה מול מקורות רשמיים.",
            )
        )
        created += 1
    if created:
        db.commit()
    return created
