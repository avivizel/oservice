def _svc(**kwargs) -> Service:
    city = kwargs.get("city", "")
    coords = city_coords(city)
    if coords and not kwargs.get("lat"):
        kwargs["lat"], kwargs["lng"] = coords
    kwargs.setdefault("status", "approved")
    kwargs.setdefault("authority", "seed")
    kwargs.setdefault("confidence", "high")
    kwargs.setdefault("last_updated", datetime.utcnow())
    kwargs.setdefault("last_verified", datetime.utcnow())
    if isinstance(kwargs.get("addiction_types"), list):
        kwargs["addiction_types"] = json.dumps(kwargs["addiction_types"], ensure_ascii=False)
    if isinstance(kwargs.get("languages"), list):
        kwargs["languages"] = json.dumps(kwargs["languages"], ensure_ascii=False)
    return Service(**kwargs)


